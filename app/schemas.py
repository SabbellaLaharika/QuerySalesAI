"""
schemas.py — Pydantic request and response schemas for the AI Sales Query API.
"""

from typing import Any, Dict, List, Union
from pydantic import BaseModel, Field, field_validator


class QueryRequest(BaseModel):
    """Request payload for POST /query endpoint."""
    question: str = Field(
        ...,
        description="Natural language question to translate into SQL and execute.",
        examples=["What is the total number of customers?"],
    )

    @field_validator("question")
    @classmethod
    def validate_question_non_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Question cannot be empty or whitespace only.")
        return v.strip()


class ChartData(BaseModel):
    """Simplified format for chart generation."""
    labels: List[str] = Field(
        default_factory=list,
        description="List of categorical labels for visualization.",
    )
    values: List[Union[int, float]] = Field(
        default_factory=list,
        description="List of corresponding numeric values.",
    )


class QueryResponse(BaseModel):
    """Response payload for successful POST /query request."""
    sql: str = Field(
        ...,
        description="The SQL query generated by the LLM.",
    )
    results: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Array of row objects from query execution.",
    )
    chart_data: ChartData = Field(
        default_factory=ChartData,
        description="Structured data for frontend charts.",
    )


class ErrorResponse(BaseModel):
    """Standardized error response payload."""
    detail: str = Field(
        ...,
        description="Human-readable explanation of the error.",
    )


def extract_chart_data(results: List[Dict[str, Any]]) -> ChartData:
    """
    Extract labels and numeric values from query results for chart visualization.
    Handles single aggregation values, grouped categories, and timeseries.
    """
    if not results:
        return ChartData(labels=[], values=[])

    labels: List[str] = []
    values: List[Union[int, float]] = []

    # Inspect first row keys
    first_row = results[0]
    keys = list(first_row.keys())

    # Case 1: Single row with single numeric column (e.g., SELECT COUNT(*) FROM customers)
    if len(results) == 1 and len(keys) == 1:
        val = first_row[keys[0]]
        if isinstance(val, (int, float)):
            return ChartData(labels=[str(keys[0])], values=[val])
        return ChartData(labels=[str(val)], values=[1])

    # Case 2: Multi-row results (e.g. grouped categories or rankings)
    # Identify label column (first text/string column) and numeric column (first or last int/float)
    label_key = None
    value_key = None

    for k in keys:
        sample_val = first_row[k]
        if isinstance(sample_val, (int, float)) and not isinstance(sample_val, bool):
            value_key = k
        elif label_key is None:
            label_key = k

    # Fallbacks if keys couldn't be determined cleanly
    if label_key is None and keys:
        label_key = keys[0]
    if value_key is None and len(keys) > 1:
        value_key = keys[1]
    elif value_key is None and keys:
        value_key = keys[0]

    for row in results:
        label = str(row.get(label_key, "")) if label_key else ""
        raw_val = row.get(value_key, 0) if value_key else 0
        if isinstance(raw_val, (int, float)) and not isinstance(raw_val, bool):
            num_val = raw_val
        else:
            try:
                num_val = float(raw_val)
            except (ValueError, TypeError):
                num_val = 0
        labels.append(label)
        values.append(num_val)

    return ChartData(labels=labels, values=values)
